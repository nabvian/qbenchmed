"""Noise sensitivity: does QAOA's answer survive realistic error rates?

Parameters are optimised ONCE on the ideal simulator and then frozen across
every noise level (spec section 47).  Re-optimising per level would measure
noise-aware training, a different question, and would mask the degradation this
experiment exists to quantify.  The ideal point is generated by the same code
path with a zero-rate model, so ideal-vs-noisy is not confounded by a different
route through the simulator.

Two channels are swept -- depolarizing and dephasing -- because they degrade a
QAOA landscape differently: dephasing destroys the relative phases the cost
layer writes, while depolarizing also drains amplitude toward the maximally
mixed state.  Within each channel the three mechanisms (single-qubit gate,
two-qubit gate, measurement) are swept one at a time so a degradation is
attributable rather than a mixture.  Measurement error is kept separate because
it corrupts the readout without touching the state and is the cheapest error to
mitigate on real hardware; dephasing on single-qubit gates is expected to leave
a depth-1 landscape untouched, and that null is checked in the report rather
than assumed.

Reported quantities per point: mean sampled energy with its standard error,
best sampled energy, and P(optimum) against the ENUMERATED ground state -- not
against the sweep's own best point, which would make every sweep look
successful by construction.  P(optimum) cannot resolve below 1/trajectories,
and that floor is recorded next to it so a reported 0.0 is read correctly.

Writes: results/noise_records.jsonl  (canonical)
        results/noise_sweep.csv      (derived view for the report)
        results/noise_env.json
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from qbm import instances as ins
from qbm import results as rs
from qbm import runner as rn

OUT = Path(__file__).resolve().parents[1] / "results"

REGIME = "degree_capped"
N_IN, K_FRAC = 10, 0.30
DEPTHS = (1, 2, 3)
SEEDS = (0, 1, 2)
TRAJECTORIES = 400
RATES = (0.0, 0.001, 0.005, 0.01, 0.02, 0.05)


MECHANISMS = ("single_qubit_error", "two_qubit_error", "measurement_error")


def sweep_points() -> list[dict]:
    """One point per (channel, mechanism, rate); rate 0 is the single ideal point.

    Each point turns on exactly ONE mechanism, so a degradation can be
    attributed to it rather than to an unresolved mixture.  Measurement error
    is swept under both channel labels even though it does not touch the state,
    because the channel field is what distinguishes gate points and dropping it
    would make the measurement rows unjoinable with the rest.
    """
    pts: list[dict] = [{}]
    for rate in RATES[1:]:
        for channel in ("depolarizing", "dephasing"):
            for mech in MECHANISMS:
                pts.append({"channel": channel, mech: rate})
    return pts


def main() -> None:
    t_start = time.perf_counter()
    OUT.mkdir(parents=True, exist_ok=True)

    n_out = int(round(N_IN * 88 / 66))
    K = max(2, round(K_FRAC * N_IN))
    points = sweep_points()

    allrecs = rs.ResultSet()
    rows = []
    for seed in SEEDS:
        inst = ins.generate(REGIME, N_IN, n_out, seed=seed)
        spec = rn.RunSpec(benchmark_id="QBM-NOISE", input_budget=K,
                          encoding="pairwise", notes="noise sensitivity sweep")
        for p in DEPTHS:
            out = rn.run_noise_sweep(inst, spec, depth=p, points=points,
                                     trajectories=TRAJECTORIES, seed=seed,
                                     n_restarts=3)
            for r in out:
                allrecs.append(r)
                nm, sm = r.noise_model, r.sampling_metrics
                active = [m for m in MECHANISMS if nm.get(m, 0.0) > 0.0]
                assert len(active) <= 1, f"more than one mechanism active: {active}"
                mech = active[0] if active else "ideal"
                rate = float(nm.get(mech, 0.0)) if active else 0.0
                rows.append({
                    "instance_seed": seed, "depth": p, "K": K,
                    "qubits": r.n_problem_variables,
                    "channel": nm.get("channel"), "mechanism": mech,
                    "rate": rate,
                    "mean_energy": sm["mean_energy"],
                    "sem_energy": sm["sem_energy"],
                    "best_energy": sm["best_energy"],
                    "optimum": r.qubo_reference_energy,
                    "optimum_probability": sm["optimum_probability"],
                    "optimum_probability_floor": sm["optimum_probability_floor"],
                    "ideal_expectation": sm["ideal_expectation"],
                    "trajectories": r.trajectories,
                    "coverage_fraction": r.coverage_fraction,
                    "feasible": r.feasible,
                })
        print(f"seed={seed} done ({time.perf_counter()-t_start:.0f}s)")

    allrecs.to_jsonl(OUT / "noise_records.jsonl")
    df = pd.DataFrame(rows)
    # Degradation relative to the ideal point of the same (seed, depth): the
    # quantity section 48 asks for, computed here rather than in the report so
    # the figure and the text cannot disagree.
    ideal = (df[df.rate == 0.0].set_index(["instance_seed", "depth"])
             .mean_energy.rename("ideal_mean_energy"))
    df = df.join(ideal, on=["instance_seed", "depth"])
    df["delta_E"] = df.mean_energy - df.ideal_mean_energy
    # Shift expressed in units of its own standard error.  A |delta_sig| below
    # 1 means the point is not resolved above trajectory sampling noise and
    # must not be read as a degradation.
    df["delta_sig"] = df.delta_E / df.sem_energy.replace(0.0, float("nan"))
    df.to_csv(OUT / "noise_sweep.csv", index=False)

    env = {"environment": rs.environment_fingerprint(),
           "regime": REGIME, "n_inputs": N_IN, "n_outcomes": n_out, "K": K,
           "depths": list(DEPTHS), "seeds": list(SEEDS), "rates": list(RATES),
           "mechanisms": list(MECHANISMS), "channels": ["depolarizing", "dephasing"],
           "trajectories": TRAJECTORIES, "parameters": "optimised once on the ideal simulator, then frozen",
           "schema_version": rs.SCHEMA_VERSION,
           "total_runtime_s": round(time.perf_counter() - t_start, 1)}
    (OUT / "noise_env.json").write_text(json.dumps(env, indent=2))
    print(f"\n{len(df)} points, {len(allrecs)} records -> {OUT}")
    print(df[df.rate > 0].groupby(["mechanism", "channel"])
          .delta_E.mean().round(2).to_string())


if __name__ == "__main__":
    main()
